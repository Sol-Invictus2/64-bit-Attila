# Generate shim_gl_gen.c: per-signature bridges for OpenGL functions with floating point arguments. Those are the only ones
# where Linux and Windows place arguments differently enough to need their own code; the rest go through one generic bridge.
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$inc = Join-Path $root '..\..\tools\zig\zig-x86_64-windows-0.17.0\lib\libc\include\any-windows-any\GL'
$seen = @{}
$short = @{}
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by gen_gl.ps1. Do not edit.')
[void]$sb.AppendLine('#define WIN32_LEAN_AND_MEAN')
[void]$sb.AppendLine('#include <windows.h>')
[void]$sb.AppendLine('#include <GL/gl.h>')
[void]$sb.AppendLine('#include <GL/glext.h>')
[void]$sb.AppendLine('#include "loader.h"')
[void]$sb.AppendLine('#include "gl_table.h"')
$table = New-Object System.Text.StringBuilder
foreach ($file in 'gl.h', 'glext.h') {
    $text = (Get-Content (Join-Path $inc $file) -Raw) -replace "\r?\n\s+", ' '
    foreach ($line in ($text -split "`n")) {
        $m = [regex]::Match($line, '^\s*(?:WINGDIAPI|GLAPI)\s+(.+?)\s+(?:APIENTRY|GLAPIENTRY)\s+(gl\w+)\s*\((.*?)\)\s*;')
        if (-not $m.Success) { continue }
        $ret = $m.Groups[1].Value.Trim(); $name = $m.Groups[2].Value; $params = $m.Groups[3].Value.Trim()
        if ($seen[$name]) { continue }
        $parts = @($params -split ',' | ForEach-Object { $_.Trim() })
        $hasFloat = $false
        foreach ($p in $parts) { if ($p -match '\b(GLfloat|GLdouble|GLclampf|GLclampd)\b' -and $p -notmatch '\*') { $hasFloat = $true } }
        if (-not $hasFloat -or $params -match '\[') {
            # no floating point and at most 6 arguments: everything travels in registers, so the short bridge (make_bridge6) is enough
            $count = if ($params -eq 'void' -or $params -eq '') { 0 } else { $parts.Count }
            if (-not $hasFloat -and $params -notmatch '\[' -and $count -le 6) { $short[$name] = $true }
            continue
        }
        $seen[$name] = $true
        $decl = @(); $call = @(); $i = 0
        foreach ($p in $parts) {
            $t = ($p -replace '\s*\b\w+\s*$', '').Trim()
            if ($p -notmatch '\s') { $t = $p }
            $t = $t -replace '\s+\*', ' *'
            $decl += "$t a$i"; $call += "a$i"; $i++
        }
        $d = $decl -join ', '; $c = $call -join ', '
        $types = ($decl | ForEach-Object { $_ -replace ' a\d+$', '' }) -join ', '
        [void]$sb.AppendLine("static $ret (__stdcall *r_$name)($types);")
        $rk = if ($ret -eq 'void') { '' } else { 'return ' }
        [void]$sb.AppendLine("SYSV static $ret w_$name($d) { ${rk}r_$name($c); }")
        [void]$table.AppendLine("    {`"$name`", (void *)w_$name, (void **)&r_$name},")
    }
}
[void]$sb.AppendLine('const GlFloatBridge g_gl_float_bridges[] = {')
[void]$sb.Append($table.ToString())
[void]$sb.AppendLine('    {0, 0, 0}};')
[void]$sb.AppendLine('const char *const g_gl_short_names[] = {')
foreach ($n in ($short.Keys | Sort-Object)) { [void]$sb.AppendLine("    `"$n`",") }
[void]$sb.AppendLine('    0};')
Set-Content -Path (Join-Path $root 'shim_gl_gen.c') -Value $sb.ToString() -Encoding ascii
"bridges generated: $($seen.Count), short-bridge names: $($short.Count)"
